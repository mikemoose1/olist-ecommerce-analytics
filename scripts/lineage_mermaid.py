#!/usr/bin/env python3
"""Write docs/LINEAGE.md: the model lineage graph as Mermaid (renders on GitHub), from target/manifest.json."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
m = json.load(open(os.path.join(ROOT, "target", "manifest.json")))
nodes = {k: v for k, v in {**m["nodes"], **m["sources"]}.items() if v["resource_type"] in ("model", "source", "seed")}
def label(k):
    v = nodes[k]
    return v["name"] if v["resource_type"] != "source" else "raw." + v["name"].replace("olist_", "").replace("_dataset", "")
layer = lambda k: ("raw" if nodes[k]["resource_type"] == "source" else "seeds" if nodes[k]["resource_type"] == "seed"
                   else nodes[k]["fqn"][1] if len(nodes[k]["fqn"]) > 2 else "models")
groups = {}
for k in nodes: groups.setdefault(layer(k), []).append(k)
lines = ["flowchart LR"]
ids = {k: f"n{i}" for i, k in enumerate(sorted(nodes))}
for g in ["raw", "seeds", "staging", "intermediate", "marts", "metrics"]:
    if g in groups:
        lines.append(f"  subgraph {g}")
        lines += [f"    {ids[k]}[{label(k)}]" for k in sorted(groups[g], key=label)]
        lines.append("  end")
for k, v in nodes.items():
    for d in v.get("depends_on", {}).get("nodes", []):
        if d in nodes: lines.append(f"  {ids[d]} --> {ids[k]}")
os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
with open(os.path.join(ROOT, "docs", "LINEAGE.md"), "w") as f:
    f.write("# Lineage\n\nGenerated by `make docs` from `target/manifest.json`. For the interactive graph run `make docs && .venv/bin/dbt docs serve`.\n\n```mermaid\n" + "\n".join(lines) + "\n```\n")
print("wrote docs/LINEAGE.md")
